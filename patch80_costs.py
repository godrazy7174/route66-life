# -*- coding: utf-8 -*-
"""작업 장소 간판에 허기·갈증·피로 소모량 표시.

  실측 소모 (코드 기준):
    채굴      허기 2   갈증 2.5  피로 5
    추적      허기 1.5 갈증 2    피로 4
    습격 계획 허기 3   갈증 3    피로 8
    배달·소몰이·강탈  소모 없음 → 간판에 '소모 없음' 명시
    숙박      허기·갈증 12 소모 (숨은 비용 — 모텔 간판에 명시)
"""
import io

P = 'ROUTE66_LIFE_EN.ow'
s = io.open(P, encoding='utf-8').read()
RN = chr(92) + 'r' + chr(92) + 'n'

def sub(old, new, cnt=1):
    global s
    assert s.count(old) == cnt, (old[:80], s.count(old))
    s = s.replace(old, new, cnt)

# 광산 — 채굴 줄에 인라인
sub('채굴 — 원석 획득' + RN,
    '채굴 — 원석 획득 (허기 2 · 갈증 2.5 · 피로 5)' + RN)

# 개활지 — 추적 소모 줄 추가
sub('드러난 30초 안에 잡아라' + RN,
    '드러난 30초 안에 잡아라' + RN + '추적 1회 — 허기 1.5 · 갈증 2 · 피로 4' + RN)

# 은신처 — 습격 계획 줄에 인라인
sub('습격 계획' + RN,
    '습격 계획 — 허기 3 · 갈증 3 · 피로 8' + RN)

# 정거장 — 소모 없음 명시
sub('보수는 거리만큼 · 화물을 든 채 털리면 빼앗긴다' + RN,
    '보수는 거리만큼 · 화물을 든 채 털리면 빼앗긴다' + RN + '허기·갈증·피로 소모 없음' + RN)

# 목장 — 소모 없음 명시
sub('소는 네가 다가간 반대쪽으로 밀린다 · 120초 제한' + RN,
    '소는 네가 다가간 반대쪽으로 밀린다 · 120초 제한' + RN + '허기·갈증·피로 소모 없음' + RN)

# 모텔 — 숙박의 숨은 비용
sub('숙박 $90 — 피로 40 회복' + RN,
    '숙박 $90 — 피로 40 회복 (자는 동안 허기·갈증 12 소모)' + RN)

io.open(P, 'w', encoding='utf-8', newline='\n').write(s)
print('작업 소모량 간판 표시: 광산·개활지·은신처·정거장·목장·모텔')
